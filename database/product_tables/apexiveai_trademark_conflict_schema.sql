CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS organizations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(255) NOT NULL,
    legal_name VARCHAR(255),
    organization_type VARCHAR(80) NOT NULL DEFAULT 'company',
    registration_number VARCHAR(120),
    country_code CHAR(2),
    email VARCHAR(255),
    phone VARCHAR(50),
    address TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive', 'suspended')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID REFERENCES organizations(id) ON DELETE SET NULL,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role VARCHAR(40) NOT NULL DEFAULT 'user'
        CHECK (role IN ('super_admin', 'admin', 'organization_admin', 'analyst', 'user')),
    status VARCHAR(30) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive', 'locked')),
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS trademark_classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_number SMALLINT NOT NULL UNIQUE CHECK (class_number BETWEEN 1 AND 45),
    title VARCHAR(255) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS trademarks (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID REFERENCES organizations(id) ON DELETE SET NULL,
    name VARCHAR(255) NOT NULL,
    owner_name VARCHAR(255),
    mark_name VARCHAR(255),
    registration_number VARCHAR(120),
    application_number VARCHAR(120),
    jurisdiction VARCHAR(120),
    nice_classes SMALLINT[] NOT NULL DEFAULT ARRAY[]::SMALLINT[],
    image_url TEXT,
    mark_type VARCHAR(40) NOT NULL DEFAULT 'logo'
        CHECK (mark_type IN ('word', 'logo', 'combined', 'other')),
    description TEXT,
    goods_services TEXT,
    country_code CHAR(2),
    status VARCHAR(40) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'filed', 'registered', 'opposed', 'expired', 'rejected', 'cancelled')),
    source VARCHAR(100),
    source_name VARCHAR(160),
    source_url TEXT,
    source_record_id VARCHAR(180),
    verification_status VARCHAR(40) NOT NULL DEFAULT 'unverified',
    created_by UUID REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS trademark_applications (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    trademark_id UUID NOT NULL REFERENCES trademarks(id) ON DELETE CASCADE,
    application_number VARCHAR(120) NOT NULL,
    registration_number VARCHAR(120),
    filing_date DATE,
    registration_date DATE,
    expiry_date DATE,
    office_code CHAR(2),
    application_status VARCHAR(50),
    source VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (office_code, application_number)
);

CREATE TABLE IF NOT EXISTS trademark_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trademark_id UUID REFERENCES trademarks(id) ON DELETE CASCADE,
    uploaded_by UUID REFERENCES users(id) ON DELETE SET NULL,
    image_role VARCHAR(40) NOT NULL DEFAULT 'primary'
        CHECK (image_role IN ('primary', 'variant', 'search_upload', 'evidence')),
    original_filename VARCHAR(255),
    storage_path TEXT,
    image_url TEXT,
    mime_type VARCHAR(120),
    file_hash CHAR(64),
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    file_size_bytes BIGINT CHECK (file_size_bytes IS NULL OR file_size_bytes >= 0),
    width INTEGER CHECK (width IS NULL OR width > 0),
    height INTEGER CHECK (height IS NULL OR height > 0),
    sha256 CHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS trademark_class_assignments (
    trademark_id UUID NOT NULL REFERENCES trademarks(id) ON DELETE CASCADE,
    class_id BIGINT NOT NULL REFERENCES trademark_classes(id) ON DELETE RESTRICT,
    PRIMARY KEY (trademark_id, class_id)
);

CREATE TABLE IF NOT EXISTS search_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID REFERENCES organizations(id) ON DELETE SET NULL,
    user_id UUID REFERENCES users(id) ON DELETE SET NULL,
    query_image_id BIGINT REFERENCES trademark_images(id) ON DELETE SET NULL,
    query_application_number VARCHAR(120),
    query_text TEXT,
    country_code CHAR(2),
    search_mode VARCHAR(40) NOT NULL DEFAULT 'combined'
        CHECK (search_mode IN ('logo', 'application_number', 'text', 'combined')),
    status VARCHAR(30) NOT NULL DEFAULT 'completed'
        CHECK (status IN ('queued', 'processing', 'completed', 'failed', 'cancelled')),
    total_results INTEGER NOT NULL DEFAULT 0 CHECK (total_results >= 0),
    parameters JSONB NOT NULL DEFAULT '{}'::jsonb,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS search_results (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    search_session_id UUID NOT NULL REFERENCES search_sessions(id) ON DELETE CASCADE,
    matched_trademark_id UUID NOT NULL REFERENCES trademarks(id) ON DELETE CASCADE,
    rank_position INTEGER NOT NULL CHECK (rank_position > 0),
    logo_similarity NUMERIC(7, 5) CHECK (logo_similarity IS NULL OR logo_similarity BETWEEN 0 AND 1),
    text_similarity NUMERIC(7, 5) CHECK (text_similarity IS NULL OR text_similarity BETWEEN 0 AND 1),
    application_number_match BOOLEAN NOT NULL DEFAULT FALSE,
    match_type VARCHAR(40) NOT NULL DEFAULT 'logo_similarity'
        CHECK (match_type IN ('logo_similarity', 'application_number', 'text_similarity', 'combined')),
    score_details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (search_session_id, matched_trademark_id),
    UNIQUE (search_session_id, rank_position)
);

CREATE TABLE IF NOT EXISTS conflict_matches (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    search_result_id UUID NOT NULL UNIQUE REFERENCES search_results(id) ON DELETE CASCADE,
    severity VARCHAR(30) NOT NULL DEFAULT 'medium'
        CHECK (severity IN ('low', 'medium', 'high', 'critical')),
    decision VARCHAR(30) NOT NULL DEFAULT 'needs_review'
        CHECK (decision IN ('needs_review', 'potential_conflict', 'no_conflict', 'confirmed_conflict')),
    explanation TEXT,
    reviewed_by UUID REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS image_embeddings (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    trademark_id UUID NOT NULL REFERENCES trademarks(id) ON DELETE CASCADE,
    image_id BIGINT NOT NULL REFERENCES trademark_images(id) ON DELETE CASCADE,
    provider VARCHAR(80) NOT NULL DEFAULT 'clip',
    model_name VARCHAR(160) NOT NULL,
    model_version VARCHAR(80),
    vector_dimension INTEGER NOT NULL CHECK (vector_dimension > 0),
    qdrant_collection VARCHAR(160) NOT NULL DEFAULT 'real_trademark_embeddings',
    qdrant_point_id VARCHAR(180) NOT NULL,
    image_hash CHAR(64),
    indexed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (qdrant_collection, qdrant_point_id),
    UNIQUE (qdrant_point_id)
);

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES users(id) ON DELETE SET NULL,
    organization_id UUID REFERENCES organizations(id) ON DELETE SET NULL,
    action VARCHAR(120) NOT NULL,
    entity_type VARCHAR(120),
    entity_id VARCHAR(180),
    ip_address INET,
    user_agent TEXT,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS api_keys (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organization_id UUID REFERENCES organizations(id) ON DELETE CASCADE,
    created_by UUID REFERENCES users(id) ON DELETE SET NULL,
    name VARCHAR(160) NOT NULL,
    key_prefix VARCHAR(24) NOT NULL,
    key_hash TEXT NOT NULL UNIQUE,
    scopes JSONB NOT NULL DEFAULT '[]'::jsonb,
    expires_at TIMESTAMPTZ,
    last_used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS system_settings (
    key VARCHAR(160) PRIMARY KEY,
    value JSONB NOT NULL DEFAULT '{}'::jsonb,
    description TEXT,
    updated_by UUID REFERENCES users(id) ON DELETE SET NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

